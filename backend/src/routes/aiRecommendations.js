
const express = require("express");
const auth = require("../middleware/auth");
const StudyPlan = require("../models/StudyPlanModel");
const Task = require("../models/Task");

const router = express.Router();

const REQUEST_TIMEOUT_MS = 20000;

// Extract a task title from common saved-plan shapes.
function getTaskTitle(item) {
    if (!item) return "Unspecified task";

    if (typeof item.title === "string" && item.title.trim()) {
        return item.title;
    }

    if (
        item.task &&
        typeof item.task.title === "string" &&
        item.task.title.trim()
    ) {
        return item.task.title;
    }

    return "Unspecified task";
}

// Extract a recorded reason from common unscheduled-task shapes.
function getUnscheduledReason(item) {
    if (!item) return "The task could not be scheduled.";

    return (
        item.reason ||
        item.unscheduledReason ||
        item.task?.reason ||
        "The scheduler could not allocate this task. Review your available study time and the task's deadline."
    );
}

// Produce useful recommendations when the AI provider is unavailable.
function buildFallbackRecommendations(context) {
    const recommendations = [];
    const scheduledTasks = context.scheduledTasks || [];
    const unscheduledTasks = context.unscheduledTasks || [];
    const pendingTasks = context.pendingTasks || [];

    // Prioritize tasks that the scheduler could not allocate.
    for (const item of unscheduledTasks) {
        if (recommendations.length >= 3) break;

        const title = getTaskTitle(item);
        const reason = getUnscheduledReason(item);

        recommendations.push(
            `**${title} — Needs attention**\n` +
            `${reason} Review your availability and identify a slot ` +
            `that can fit the task before its exam deadline.`
        );
    }

    // Help the student prepare for scheduled tasks.
    for (const item of scheduledTasks) {
        if (recommendations.length >= 5) break;

        const title = getTaskTitle(item);
        const priority = item.priority || item.task?.priority;
        const date =
            item.date ||
            item.scheduledDate ||
            item.studyDate;
        const startTime = item.startTime;
        const endTime = item.endTime;

        let timing = "";

        if (date) {
            timing = ` Scheduled date: ${date}.`;

            if (startTime && endTime) {
                timing =
                    ` Scheduled for ${date}, from ` +
                    `${startTime} to ${endTime}.`;
            }
        }

        const priorityText = priority
            ? ` It has ${priority} priority.`
            : "";

        recommendations.push(
            `**${title} — Prepare for your session**\n` +
            `Review the relevant concepts and prepare one specific ` +
            `practice activity before starting.${priorityText}${timing}`
        );
    }

    // If the saved plan has no scheduled or unscheduled task details,
    // use pending tasks from the database without inventing time slots.
    for (const task of pendingTasks) {
        if (recommendations.length >= 5) break;

        const alreadyIncluded = recommendations.some((item) =>
            item.includes(task.title)
        );

        if (alreadyIncluded) continue;

        const duration =
            task.remainingMinutes ?? task.estimatedMinutes;

        const examText = task.examDate
            ? ` Its exam date is ${task.examDate}.`
            : "";

        recommendations.push(
            `**${task.title} — Review remaining work**\n` +
            `This task is still pending` +
            (duration != null
                ? `, with ${duration} minutes of estimated remaining work`
                : "") +
            `.${examText} Check the saved plan to confirm when it can be studied.`
        );
    }

    if (recommendations.length === 0) {
        recommendations.push(
            "**Review your study plan**\n" +
            "Check your pending tasks, exam dates, and available slots. " +
            "Update any missing information and generate a plan before " +
            "requesting more specific recommendations."
        );
    }

    return (
        "Plan-Based Recommendations\n\n" +
        recommendations
            .slice(0, 5)
            .map((item, index) => `${index + 1}. ${item}`)
            .join("\n\n") +
        "\n\nThese recommendations are based on your saved study data, " +
        "not generated by the AI provider."
    );
}

router.post("/recommendations", auth, async (req, res) => {
    try {
        const userId = req.user._id;

        const [latestPlan, pendingTasks] = await Promise.all([
            StudyPlan.findOne({ userId })
                .sort({ createdAt: -1 })
                .lean(),

            Task.find({ userId, status: "Pending" })
                .select(
                    "title estimatedMinutes remainingMinutes priority subjectId"
                )
                .populate({
                    path: "subjectId",
                    match: { userId },
                    select: "subjectName examId",
                    populate: {
                        path: "examId",
                        match: { userId },
                        select: "examName examDate",
                    },
                })
                .lean(),
        ]);

        if (!latestPlan) {
            return res.status(400).json({
                message:
                    "Generate a study plan before requesting recommendations.",
            });
        }

        const context = {
            pendingTasks: pendingTasks
                .filter((task) => task.subjectId?.examId)
                .map((task) => ({
                    title: task.title,
                    subject: task.subjectId.subjectName,
                    examName: task.subjectId.examId.examName,
                    examDate: task.subjectId.examId.examDate,
                    priority: task.priority,
                    estimatedMinutes: task.estimatedMinutes,
                    remainingMinutes:
                        task.remainingMinutes ?? task.estimatedMinutes,
                })),

            scheduledTasks: latestPlan.scheduledTasks || [],
            unscheduledTasks: latestPlan.unscheduledTasks || [],
            availableSlots: latestPlan.availableSlotsSnapshot || [],
            generatedAt: latestPlan.createdAt,
        };

        const apiKey = process.env.GEMINI_API_KEY;

        // Use saved-plan recommendations if Gemini is not configured.
        if (!apiKey) {
            return res.status(200).json({
                recommendation: buildFallbackRecommendations(context),
                source: "fallback",
                generatedAt: new Date().toISOString(),
            });
        }

        const model = process.env.GEMINI_MODEL || "gemini-3.8-flash";

        const controller = new AbortController();

        const timeout = setTimeout(
            () => controller.abort(),
            REQUEST_TIMEOUT_MS
        );

        let response;
        let result;

        try {
            const url =
                `https://generativelanguage.googleapis.com/v1beta/models/` +
                `${encodeURIComponent(model)}:generateContent` +
                `?key=${encodeURIComponent(apiKey)}`;

            response = await fetch(url, {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                },
                signal: controller.signal,
                body: JSON.stringify({
                    systemInstruction: {
                        parts: [
                            {
                                text: `
You are a practical study coach inside an AI Study Planner.

Use only the supplied data. The deterministic scheduler is authoritative
for task allocation, time slots, availability, and deadlines.

Give 4-5 specific recommendations when the data supports them.
For each recommendation:
- Identify the exact task title.
- Explain why it needs attention using the supplied data.
- Give one concrete action the student can take.
- Mention dates and times only when supplied.
- Address unscheduled tasks and their recorded reasons.
- Avoid repetitive or generic advice.

Never invent availability, deadlines, task status, or schedule changes.
Do not calculate a new schedule or claim an unscheduled task is scheduled.
Do not treat advisory recommendations as changes to the saved plan.
Write a short heading and numbered recommendations using complete
sentences. If the supplied data is insufficient, say so briefly.
`,
                            },
                        ],
                    },
                    contents: [
                        {
                            role: "user",
                            parts: [
                                {
                                    text:
                                        "Recommend practical next actions " +
                                        "based on this saved study plan:\n" +
                                        JSON.stringify(context),
                                },
                            ],
                        },
                    ],
                    generationConfig: {
                        temperature: 0.3,
                        maxOutputTokens: 800,
                    },
                }),
            });

            result = await response.json();
        } catch (error) {
            console.error(
                "Gemini recommendation request failed:",
                error.name === "AbortError"
                    ? "Request timed out"
                    : error.message
            );

            return res.status(200).json({
                recommendation: buildFallbackRecommendations(context),
                source: "fallback",
                generatedAt: new Date().toISOString(),
            });
        } finally {
            clearTimeout(timeout);
        }

        if (!response.ok) {
            console.error(
                "Gemini recommendation API error:",
                result?.error?.message || response.status
            );

            return res.status(200).json({
                recommendation: buildFallbackRecommendations(context),
                source: "fallback",
                generatedAt: new Date().toISOString(),
            });
        }

        const candidate = result.candidates?.[0];

        const recommendation = (
            candidate?.content?.parts || []
        )
            .map((part) => part.text || "")
            .join("\n")
            .trim();

        if (
            !recommendation ||
            candidate?.finishReason === "MAX_TOKENS"
        ) {
            return res.status(200).json({
                recommendation: buildFallbackRecommendations(context),
                source: "fallback",
                generatedAt: new Date().toISOString(),
            });
        }

        return res.status(200).json({
            recommendation,
            source: "ai",
            generatedAt: new Date().toISOString(),
        });
    } catch (error) {
        console.error("AI recommendation error:", error);

        return res.status(500).json({
            message: "Failed to prepare study recommendations.",
        });
    }
});

module.exports = router;
